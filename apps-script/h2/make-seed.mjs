// H2 test helper (NOT part of the product bundle). Generates dist/H2Seed.js, a function that writes the
// sample plan into the hidden `_plan` tab of a test spreadsheet. The owner email comes from the
// environment so a real address is never committed:  H2_OWNER_EMAIL=you@example.com node h2/make-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";

const owner = process.env.H2_OWNER_EMAIL;
if (!owner) throw new Error("Set H2_OWNER_EMAIL to the address that should receive test emails.");

const plan = JSON.parse(readFileSync("../packages/plan-schema/test/fixtures/valid-example.json", "utf8"));
plan.owner = { name: "Test Owner", email: owner };
// Keep the example contributor (example.com): nothing is ever sent to it, alerts go to the owner only.

const json = JSON.stringify(plan);
const chunks = [];
for (let i = 0; i < json.length; i += 40000) chunks.push(json.slice(i, i + 40000));

writeFileSync(
  "dist/H2Seed.js",
  `// Generated by h2/make-seed.mjs. Test only. Run once from the editor, then delete this file.\n` +
    `function h2SeedPlan() {\n` +
    `  var ss = SpreadsheetApp.getActive();\n` +
    `  var sh = ss.getSheetByName("_plan") || ss.insertSheet("_plan");\n` +
    `  sh.clear();\n` +
    `  var chunks = ${JSON.stringify(chunks)};\n` +
    `  sh.getRange(1, 1, chunks.length, 1).setNumberFormat("@").setValues(chunks.map(function (c) { return [c]; }));\n` +
    `  try { SpreadsheetApp.getUi().alert("Plan written to _plan (" + chunks.length + " row). Now use the menu."); }\n` +
    `  catch (e) { Logger.log("Plan written to _plan (" + chunks.length + " row). Reload the sheet and use the menu."); }\n` +
    `}\n`,
);
console.log("Wrote dist/H2Seed.js (" + json.length + " characters of plan)");
